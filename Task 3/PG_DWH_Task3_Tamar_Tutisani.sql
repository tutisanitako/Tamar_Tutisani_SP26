-- TASK 2: UNDERSTANDING INHERITED TABLES
-----------------------------------------------------------------------------
-- Inheritance lets a child table share all columns of a parent while
-- adding its own. Queries on the parent automatically include child rows
-- unless ONLY is specified.

-- 1. Create a child table that inherits from person
DROP TABLE IF EXISTS labs.users CASCADE;

CREATE TABLE labs.users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login   VARCHAR(30)
) INHERITS (labs.person);

-- 2. Insert rows into users (child)
INSERT INTO labs.users (id, name, login)
SELECT v.id, v.name, v.login
FROM (VALUES
    (1, 'new Bob', 'NewLogin'),
    (999, 'TestUser', 'TestLogin')
) AS v(id, name, login)
WHERE NOT EXISTS (
    SELECT 1
    FROM labs.users u
    WHERE u.id = v.id
);

-- 3. Selects: observe the difference between person, ONLY person, users
SELECT * 
FROM labs.users;
-- Returns only users rows (2 rows)
-- this is shown in screenshot task2_1.png

SELECT * 
FROM labs.person;
-- Returns person rows (3 original) PLUS users rows (2) = 5 rows total
-- Child rows are visible in the parent query by default
-- this is shown in screenshot task2_2.png

SELECT * 
FROM ONLY labs.person;
-- Returns only the 3 original person rows, ONLY excludes child tables
-- this is shown in screenshot task2_3.png

-- 4. UPDATE on parent affects BOTH parent-only and child rows
UPDATE labs.person
SET name = 'not Bob'
WHERE id = 1;
-- This updates id=1 in BOTH person (Bob row) AND users (new Bob row)
-- because users inherits from person

SELECT * 
FROM labs.person; -- shows 'not Bob' in two places
-- this is shown in screenshot task2_4.png

SELECT * 
FROM labs.users; -- also shows 'not Bob'
-- this is shown in screenshot task2_5.png

-- Rewrite: change name ONLY in person table (not users)
UPDATE ONLY labs.person
SET name = 'Bob_restored'
WHERE id = 1;

SELECT * 
FROM labs.person; -- person row restored; users row still 'not Bob'
-- this is shown in screenshot task2_6.png

SELECT * 
FROM labs.users; -- users row unchanged
-- this is shown in screenshot task2_7.png

-- 5. ALTER parent: columns propagate to child; CHECK with NO INHERIT does NOT
ALTER TABLE labs.person 
ADD COLUMN IF NOT EXISTS status INTEGER DEFAULT 0;
-- status column now appears in BOTH labs.person and labs.users

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_person_status'
    ) THEN
        ALTER TABLE labs.person
            ADD CONSTRAINT chk_person_status CHECK (status IN (0, 1)) NO INHERIT;
		-- NO INHERIT: this check constraint stays on labs.person only, not labs.users
		-- labs.users can store status = 5 without violating anything
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_person_id_name'
    ) THEN
        ALTER TABLE labs.person
            ADD CONSTRAINT uq_person_id_name UNIQUE (id, name);
		-- UNIQUE constraints on parent are NOT inherited by child tables
		-- (unlike CHECK constraints which ARE inherited unless NO INHERIT is specified)
    END IF;
END $$;

-- Inspect constraints on both tables
SELECT conname,
       contype,
       coninhcount,
       connoinherit
FROM pg_constraint
WHERE conrelid IN ('labs.person'::regclass, 'labs.users'::regclass);
-- this is shown in screenshot task2_8.png

/*
EXPECTED OBSERVATIONS:
- Querying parent (person) without ONLY pulls in child (users) rows automatically
- ONLY keyword restricts queries/DML to the parent table exclusively
- CHECK constraints inherited by default; NO INHERIT stops propagation
- UNIQUE, PRIMARY KEY, FOREIGN KEY, INDEX — NOT inherited (must be created
  separately on each child if needed)
- Column additions propagate to child tables automatically
- Good use case: partitioning by range/type when declarative partitioning
  isn't needed; also used in multi-tenant scenarios
*/


