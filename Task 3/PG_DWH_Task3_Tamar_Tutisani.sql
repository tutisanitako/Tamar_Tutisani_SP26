-- TASK 3: BRIN vs B-TREE INDEXES
-----------------------------------------------------------------------------
-- BRIN (Block Range Index) stores min/max per block range instead of
-- per-row entries. It is tiny and fast to build but only useful when data
-- is physically ordered by the indexed column (e.g. time-series loaded
-- sequentially). B-Tree is the standard balanced tree index.

-- 1. Create the test table
DROP TABLE IF EXISTS labs.test_index;

CREATE TABLE labs.test_index (
    num FLOAT NOT NULL,
    load_date TIMESTAMPTZ NOT NULL
);

-- 2. Fill with ~5 years of 10-second-interval timestamps (~15.7M rows)
--    load_date is naturally ordered (sequential insert) = ideal for BRIN
INSERT INTO labs.test_index (num, load_date)
SELECT random(),
       x
FROM generate_series(
    '2017-01-01 0:00'::TIMESTAMPTZ,
    '2021-12-31 23:59:59'::TIMESTAMPTZ,
    '10 seconds'::INTERVAL
) x;
-- execution time 1m 17s

-- Check table size
SELECT pg_size_pretty(pg_relation_size('labs.test_index')) AS table_size;
-- this is shown in screenshot task3_1.png

-- 3. Baseline query (no index)
EXPLAIN ANALYZE
SELECT date_trunc('year', load_date) AS year,
       max(num) AS max_num
FROM labs.test_index
WHERE load_date BETWEEN '2021-09-01 0:00' AND '2021-10-31 11:59:59'
GROUP BY 1
ORDER BY 1;
-- Expect: Seq Scan, reads the entire table
-- this is shown in screenshot task3_2.png

-- 4a. Create B-Tree index and measure creation time
CREATE INDEX idx_test_index_btree ON labs.test_index USING btree (load_date);
-- execution time 27s

-- 4b. Re-run the query with B-Tree index active
EXPLAIN ANALYZE
SELECT date_trunc('year', load_date) AS year,
       max(num) AS max_num
FROM labs.test_index
WHERE load_date BETWEEN '2021-09-01 0:00' AND 
						'2021-10-31 11:59:59'
GROUP BY 1
ORDER BY 1;
-- Expect: Index Scan or Bitmap Index Scan, much faster for range queries
-- this is shown in screenshot task3_3.png

-- 4c. Check B-Tree index size
SELECT pg_size_pretty(pg_relation_size('idx_test_index_btree')) AS btree_index_size;
-- this is shown in screenshot task3_4.png

-- 4d. Drop B-Tree index
DROP INDEX IF EXISTS labs.idx_test_index_btree;

-- 5a. Create BRIN index and measure creation time (should be much faster)
CREATE INDEX idx_test_index_brin ON labs.test_index USING brin (load_date);
-- execution time 1.861s
-- this is shown in screenshot task3_5.png

-- 5b. Re-run the query with BRIN index active
EXPLAIN ANALYZE
SELECT date_trunc('year', load_date) AS year,
       max(num) AS max_num
FROM labs.test_index
WHERE load_date BETWEEN '2021-09-01 0:00' AND 
						'2021-10-31 11:59:59'
GROUP BY 1
ORDER BY 1;
-- Expect: Bitmap Index Scan using BRIN, fast because load_date is sequential
-- this is shown in screenshot task3_6.png

-- 5c. Check BRIN index size
SELECT pg_size_pretty(pg_relation_size('idx_test_index_brin')) AS brin_index_size;
-- this is shown in screenshot task3_7.png

-- 5d. Drop BRIN index
DROP INDEX IF EXISTS labs.idx_test_index_brin;

-- 6. Cleanup
DROP TABLE IF EXISTS labs.test_index;

/*
EXPECTED OBSERVATIONS:
- B-Tree:
    * Creation: slower (must build a full sorted tree over all rows)
    * Query: faster (direct range scan on the tree)
    * Size: large (stores an entry per indexed row value)
- BRIN:
    * Creation: much faster (just stores min/max per ~128-page block)
    * Query: fast when data is physically sequential (our case: time-series)
    * Size: tiny — often 100-1000x smaller than B-Tree
- Key insight: BRIN only works well when the physical row order correlates
  with the index column order. For random data, BRIN degrades to a full
  table scan. For our DWH fact tables loaded in date order, BRIN on
  EVENT_DT is a valid lightweight alternative to B-Tree.
*/


