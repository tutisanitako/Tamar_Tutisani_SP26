-- TASK 1: PERFORMANCE WITH UNLOGGED TABLES
-----------------------------------------------------------------------------
-- Unlogged tables skip the Write-Ahead Log (WAL). Because WAL writes are
-- the bottleneck for INSERT-heavy workloads, unlogged tables are typically
-- 3-10x faster to write to. Trade-off: data is truncated on crash/restart.

-- 1. Create a regular (logged) table
DROP TABLE IF EXISTS labs.test_simple;

CREATE TABLE labs.test_simple (
    a INT,
    b INT
);

-- 2a. Inserting 1,000,000 rows into logged table and noting the time
INSERT INTO labs.test_simple
SELECT generate_series(1, 1000000);
-- this is shown in screenshot task1_1.png

-- 2b. Insert 5,000,000 more rows
INSERT INTO labs.test_simple
SELECT generate_series(1, 5000000);
-- this is shown in screenshot task1_2.png

-- 3. Create an UNLOGGED table with the same structure
DROP TABLE IF EXISTS labs.test_unlogged;

CREATE UNLOGGED TABLE labs.test_unlogged (
    a INT,
    b INT
);

-- 4a. Insert 1,000,000 rows into unlogged table
INSERT INTO labs.test_unlogged
SELECT generate_series(1, 1000000);
-- this is shown in screenshot task1_3.png

-- 4b. Insert 5,000,000 more rows
INSERT INTO labs.test_unlogged
SELECT generate_series(1, 5000000);
-- this is shown in screenshot task1_4.png

-- Compare row counts to confirm both tables have the same data
SELECT 'test_simple' AS table_name, 
	   COUNT(*) 
FROM labs.test_simple
UNION ALL
SELECT 'test_unlogged' AS table_name,
	   COUNT(*) 
FROM labs.test_unlogged;
-- this is shown in screenshot task1_5.png

/*
EXPECTED OBSERVATIONS:
- Unlogged inserts are noticeably faster (often 3-10x) because PostgreSQL
  skips writing to WAL. WAL is the main write bottleneck for small random
  INSERTs.
- For the 5M insert, the gap is even more pronounced.
- Use cases for unlogged: staging/temp ETL data, session data, anything
  that can be rebuilt if the server crashes (e.g. our SA layer SRC_ tables
  during ETL runs — we can always re-load from the EXT_ foreign tables).
- Downside: on crash PostgreSQL TRUNCATES the unlogged table automatically
  on restart. Also, unlogged tables are not replicated.
*/


