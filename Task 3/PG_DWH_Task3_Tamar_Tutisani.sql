-- TASK 5: CSV FILE AS A FOREIGN TABLE + MATERIALIZED VIEW
-----------------------------------------------------------------------------
-- file_fdw lets PostgreSQL read a CSV on disk as if it were a regular table.
-- A materialized view caches the result set so repeated queries avoid
-- re-reading the file each time, important for large CSVs or slow storage.

-- 1. Install file_fdw extension and create the server
--    (requires superuser; run once per database)
CREATE EXTENSION IF NOT EXISTS file_fdw;

CREATE SERVER IF NOT EXISTS test_import
    FOREIGN DATA WRAPPER file_fdw;

-- 2. Create the foreign table pointing to cities_list.csv

DROP FOREIGN TABLE IF EXISTS labs.test_foreign_table;

CREATE FOREIGN TABLE labs.test_foreign_table (
    LatD INT,
    LatM INT,
    LatS INT,
    NS TEXT,
    LonD INT,
    LonM INT,
    LonS INT,
    EW TEXT,
    City TEXT,
    State TEXT
)
SERVER test_import
OPTIONS (
    filename 'C:/Program Files/PostgreSQL/18/data/cities_list.csv',
    format 'csv',
    header 'true',
    delimiter ','
);
-- this is shown in screenshot task5_1.png

-- 3. Select all rows and count from the foreign table
SELECT *
FROM labs.test_foreign_table;
-- this is shown in screenshot task5_2.png

SELECT count(*) AS total_cities
FROM labs.test_foreign_table;
-- Expected: 128 rows (the full cities_list.csv)
-- this is shown in screenshot task5_3.png

-- 4. Create a materialized view on top of the foreign table
--    Materialized views store the result set physically, unlike regular views.
--    Queries against the mview hit local storage, not the CSV file each time.

DROP MATERIALIZED VIEW IF EXISTS labs.mv_cities;

CREATE MATERIALIZED VIEW labs.mv_cities AS
    SELECT *
    FROM labs.test_foreign_table;

-- Select from the materialized view
SELECT *
FROM labs.mv_cities;
-- this is shown in screenshot task5_4.png

SELECT count(*) AS mview_count
FROM labs.mv_cities;
-- Should match the foreign table count
-- this is shown in screenshot task5_5.png

-- 5. Simulate deletion from file:
--    Open cities_list.csv in a text editor and delete a few rows, then save.
--    Now query the foreign table again,count drops immediately (reads live file).
SELECT count(*) AS foreign_table_count_after_deletion
FROM labs.test_foreign_table;
-- this is shown in screenshot task5_6.png

-- But the materialized view still shows the OLD count (it is stale/cached):
SELECT count(*) AS mview_count_before_refresh
FROM labs.mv_cities;
-- this is shown in screenshot task5_7.png

-- 6. Refresh the materialized view to sync with the updated CSV
REFRESH MATERIALIZED VIEW labs.mv_cities;

SELECT count(*) AS mview_count_after_refresh
FROM labs.mv_cities;
-- Now matches the foreign table count (deleted rows no longer appear)
-- this is shown in screenshot task5_8.png

/*
EXPECTED OBSERVATIONS:
- Foreign table (file_fdw): reads the CSV file on every query — always
  shows current file state. No data is stored in PostgreSQL.
- Materialized view: stores a physical snapshot of the data at refresh time.
  Queries are fast (local table scan). But data goes stale until you REFRESH.
- REFRESH MATERIALIZED VIEW is a blocking operation (table locked during
  refresh). Use REFRESH MATERIALIZED VIEW CONCURRENTLY to allow reads during
  refresh (requires a UNIQUE index on the view first).
- Real-world DWH parallel: our EXT_ foreign tables (file_fdw on CSVs) are
  like the foreign table here. Our SRC_ tables are like the materialized view,
  a snapshot taken at load time, refreshed on each ETL run.
*/


