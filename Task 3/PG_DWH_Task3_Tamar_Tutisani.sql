-- TASK 4: GIN vs GiST INDEXES
-----------------------------------------------------------------------------
-- Both GIN and GiST support non-standard search operators (LIKE, full-text,
-- array containment). pg_trgm extension enables trigram-based LIKE matching
-- using either index type.

-- Prerequisite: pg_trgm extension (enables LIKE/ILIKE index support)
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 1. Create and fill the test table
DROP TABLE IF EXISTS labs.test_index;

CREATE TABLE labs.test_index AS
SELECT id,
       md5(id::TEXT) AS t_hash
FROM generate_series(1, 10000000) AS id;
-- this is shown in screenshot task4_1.png

-- Check table size
SELECT pg_size_pretty(pg_relation_size('labs.test_index')) AS table_size;
-- this is shown in screenshot task4_2.png

-- 2. Baseline LIKE query (no index)
EXPLAIN ANALYZE
SELECT *
FROM labs.test_index
WHERE t_hash LIKE '%ceea167a5a%';
-- Expect: Seq Scan, slow, reads all 10M rows
-- this is shown in screenshot task4_3.png

-- 3a. Create GiST index using trigram operators
CREATE INDEX idx_test_index_gist
    ON labs.test_index
    USING gist (t_hash gist_trgm_ops);
-- this is shown in screenshot task4_4.png

-- 3b. Re-run the LIKE query with GiST index active
EXPLAIN ANALYZE
SELECT *
FROM labs.test_index
WHERE t_hash LIKE '%ceea167a5a%';
-- Expect: Index Scan using GiST, faster than Seq Scan
-- this is shown in screenshot task4_5.png

-- 3c. Check GiST index size
SELECT pg_size_pretty(pg_relation_size('idx_test_index_gist')) AS gist_index_size;
-- 1769 MB, this is shown in screenshot task4_6.png


-- 3d. Drop GiST index
DROP INDEX IF EXISTS labs.idx_test_index_gist;

-- 4a. Create GIN index using trigram operators
CREATE INDEX idx_test_index_gin
    ON labs.test_index
    USING gin (t_hash gin_trgm_ops);
-- this is shown in screenshot task4_7.png

-- 4b. Re-run the LIKE query with GIN index active
EXPLAIN ANALYZE
SELECT *
FROM labs.test_index
WHERE t_hash LIKE '%ceea167a5a%';
-- Expect: Bitmap Index Scan using GIN, typically faster than GiST for LIKE
-- this is shown in screenshot task4_8.png

-- 4c. Check GIN index size
SELECT pg_size_pretty(pg_relation_size('idx_test_index_gin')) AS gin_index_size;
-- 600 MB, this is shown in screenshot task4_9.png

-- 4d. Drop GIN index
DROP INDEX IF EXISTS labs.idx_test_index_gin;

-- 5. Cleanup
DROP TABLE IF EXISTS labs.test_index;

/*
OBSERVATIONS:
- Baseline (no index): Seq Scan, reads all 10M rows, slow.

- GIN is faster for LIKE queries because it stores an exact inverted index
  of trigrams with no false positives, so no table recheck is needed.
  GiST uses a lossy tree structure and must recheck matches against the
  actual rows, adding overhead.

- GiST is larger than GIN here (1769 MB vs 600 MB) because its tree
  structure requires internal node pages and padding. GIN stores each
  unique trigram once with compact posting lists.

- GiST builds faster and handles frequent updates better. GIN is the
  better choice for read-heavy workloads with rare updates, which matches
  our DWH dimension tables.
*/


